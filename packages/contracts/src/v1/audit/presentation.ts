export const AUDIT_ACTION_LABELS: Readonly<Record<string, string>> = Object.freeze(Object.fromEntries(AUDIT_ACTION_CODES.map(action => {
  const [subject, ...suffix] = action.split('.')
  return [action, overrides[action] ?? (subjects[subject!] && verbs[suffix.join('.')] ? `${subjects[subject!]}: ${verbs[suffix.join('.')]}` : 'Di?er i?lem kayd?')]
})))
export function auditActionLabel(action: string): string { return AUDIT_ACTION_LABELS[action] ?? 'Diğer işlem kaydı' }

export const AUDIT_CATEGORIES = { cases: 'Dosya kayıtları', files: 'Klasör ve belgeler', users: 'Kullanıcılar', permissions: 'Yetkiler', auth: 'Oturum ve güvenlik', access: 'Görüntüleme ve istekler', other: 'Analiz ve diğer işlemler' } as const
export type AuditCategory = keyof typeof AUDIT_CATEGORIES
export function auditCategory(action: string): AuditCategory {
  const subject = action.split('.')[0]
  if (subject === 'permissions') return 'permissions'
  if (subject === 'user') return 'users'
  if (subject === 'auth') return 'auth'
  if (subject === 'access' || subject === 'request') return 'access'
  if (subject && ['case', 'cases', 'case_note', 'case_task', 'case_lifecycle', 'case_inventory'].includes(subject)) return 'cases'
  if (subject && ['document', 'file_operation', 'photo', 'document_text', 'document_page_ocr', 'document_page_ocr_source_reference', 'storage_root'].includes(subject)) return 'files'
  return 'other'
}
export const AUDIT_RESULTS = { success: 'Başarılı', failed: 'Başarısız', rejected: 'Reddedildi', pending: 'Bekliyor / inceleme gerekli', cancelled: 'İptal edildi', recorded: 'Kaydedildi' } as const
export type AuditResult = keyof typeof AUDIT_RESULTS
export function auditResult(action: string, details: Record<string, unknown> = {}): AuditResult {
  const status = details.statusCode
  if (typeof status === 'number' && status >= 500 || /(?:failed|account_locked|login_rate_limited|dead_letter|verification_missing)$/.test(action)) return 'failed'
  if (typeof status === 'number' && status >= 400 || /(?:rejected|close_blocked)$/.test(action)) return 'rejected'
  if (!Object.hasOwn(AUDIT_ACTION_LABELS, action)) return 'recorded'
  if (/cancelled$/.test(action)) return 'cancelled'
  if (/(?:planned|queued|started|applying|pending|required|stale|unknown|conflict_detected|submitted|quarantined|partial|requested|low_confidence|budget_blocked|provider_disabled|network_attempt_blocked|retry_scheduled|workspace_verifying|document_missing)$/.test(action)) return 'pending'
  if (/(?:created|updated|deleted|completed|approved|verified|finalized|registered|saved|viewed|succeeded|logout|google_login|changed|assigned|repaired|reconciled|maintained|ready|bound|exported|closed|reopened|revised|corrected|confirmed|switched|relocated|read|linked|connected|disconnected|published|promoted|resolved|evaluated|generated|imported|applied)$/.test(action)) return 'success'
  return 'recorded'
}
