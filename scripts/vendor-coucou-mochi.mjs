import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

// Pin the drawing code so regeneration never silently changes the character.
const revision = '1dc314f632ff646b44191dbd4e89b042e07b3670'
const upstream = `https://raw.githubusercontent.com/Louis-CFM/coucou/${revision}/`
const output = new URL('../public/vendor/coucou/', import.meta.url)
const files = ['windows/src/mochi/engine.ts', 'windows/src/mochi/outfits.ts', 'windows/src/core/anim.ts', 'windows/src/core/fonts.ts', 'LICENSE', 'LICENSE-ASSETS.md']

for (const path of files) {
  const response = await fetch(`${upstream}${path}`)
  if (!response.ok) throw new Error(`Coucou ${path}: HTTP ${response.status}`)
  let source = await response.text()
  let relative = path.replace('windows/src/', '')
  if (path.endsWith('.ts')) {
    // This integration has no audio player. Remove only upstream audio calls;
    // the drawing, geometry and animation timings are retained.
    if (path.endsWith('/engine.ts')) {
      const calls = source.match(/^.*Sound\.play.*\r?\n/gm) ?? []
      if (calls.length !== 4) throw new Error('Review upstream sound integration before regenerating')
      source = source.replace(/^import \{ Sound \} from .*\r?\n/m, '').replace(/^.*Sound\.play.*\r?\n/gm, '')
      // Allow contrasting eyes on dark user-selected bodies without recoloring the body.
      const bodyColor = 'bodyColor: RGB | null = null;'
      const eyeInk = 'const ink = this.isMini ? MINI_INK : INK;'
      if (source.split(bodyColor).length !== 2 || source.split(eyeInk).length !== 2) throw new Error('Review upstream character color integration before regenerating')
      source = source.replace(bodyColor, `${bodyColor}\n  eyeColor: string | null = null;`)
        .replace(eyeInk, 'const ink = this.eyeColor ?? (this.isMini ? MINI_INK : INK);')
    }
    let code = ts.transpileModule(source, {
      fileName: path,
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022, newLine: ts.NewLineKind.LineFeed },
    }).outputText
    code = code.replace(/from "([^"]+)"/g, 'from "$1.js"')
    source = `// Vendored from Louis-CFM/coucou @ ${revision}.\n// Generated by scripts/vendor-coucou-mochi.mjs; do not edit. See ../LICENSE and ../LICENSE-ASSETS.md.\n${code}`
    relative = relative.replace(/\.ts$/, '.js')
  }
  const target = new URL(relative, output)
  await mkdir(fileURLToPath(new URL('.', target)), { recursive: true })
  await writeFile(target, source, 'utf8')
}
