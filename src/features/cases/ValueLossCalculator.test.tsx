import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { describe, expect, it, vi } from 'vitest'
import { eksistCaseDataSchema } from '@hasarbotu/contracts'
import { SessionContext, type SessionContextValue } from '../../app/sessionContext'
import type { ValueLossCalculatorPort } from '../../data/valueLossCalculatorPort'
import type { CaseRecord } from '../../types/case'
import { ValueLossCalculator } from './ValueLossCalculator'

const item = { caseId: 'case-1', type: 'Trafik', lossDate: '2026-10-01', estimatedDamage: 100_000 } as CaseRecord
const session = { user: { id: 'user-1', organizationId: 'org-1', roles: ['expert'] }, reportUnauthorized: vi.fn() } as unknown as SessionContextValue
const result = { amountMinor: 5_500_000, ruleVersion: 'real-market-analysis/2026-07-01/1.0.0', calculationMethod: 'real_market_analysis' as const, issues: [] }
function sourceCase(vehicleFields: Record<string, string>): CaseRecord {
  return { ...item, eksist: eksistCaseDataSchema.parse({ sourceId: '00000000-0000-7000-8000-000000000050', assignmentDate: '2026-10-02', assignmentDateText: '02.10.2026', insurerName: 'Test Sigorta', expertName: 'Test Eksper', expertLicenseNumber: '', corporateExpertLicenseNumber: '', serviceName: '', serviceRevised: false, vehicleFields }) }
}
function fixture(): ValueLossCalculatorPort {
  return { load: vi.fn().mockResolvedValue(null), catalog: vi.fn().mockResolvedValue({ vehicleGroupCode: 'A', ruleIdentity: result.ruleVersion, parts: [{ stableRuleId: 'part-1', label: 'SOL ÇAMURLUK', supportedOperations: ['replacement','repair','paint'], coefficients: { replacement: '1', repair: { light: '0.5', medium: '1', heavy: '1.5' }, paint: { full: '1', local: '0.5' } } }] }), calculate: vi.fn().mockResolvedValue(result) }
}
function view(port: ValueLossCalculatorPort, current = item, user = session) { return <SessionContext.Provider value={user}><ValueLossCalculator item={current} source="api" port={port} /></SessionContext.Provider> }
async function fill() {
  fireEvent.change(screen.getByLabelText('Model yılı'), { target: { value: '2024' } })
  fireEvent.change(screen.getByLabelText('Kilometre'), { target: { value: '50000' } })
  fireEvent.change(screen.getByLabelText('Rayiç bedeli (TL)'), { target: { value: '1.000.000' } })
  await waitFor(() => expect(screen.getByRole('combobox', { name: 'Hasarlı parça' })).toBeEnabled())
  await userEvent.click(screen.getByRole('combobox', { name: 'Hasarlı parça' }))
  await userEvent.click(screen.getByRole('option', { name: 'SOL ÇAMURLUK' }))
  fireEvent.click(screen.getByRole('button', { name: 'Ekle' }))
}

describe('simple value loss calculator', () => {
  it('automatically fills available case and SBM fields when the calculator opens', async () => {
    const port = fixture()
    const current = sourceCase({ Marka: 'FORD', 'Araç Tipi': 'TRANSIT', 'Model Yılı': '2021', 'Araç Tarife Grubu': 'KAMYONET', 'Kasa Tipi': 'Panelvan' })
    render(view(port, current))
    expect(screen.getByLabelText('Kaza tarihi')).toHaveValue('2026-10-01')
    expect(screen.getByLabelText('Araç türü')).toHaveValue('KAMYONET')
    expect(screen.getByLabelText('Kasa / araç yapısı')).toHaveValue('panel_van')
    expect(screen.getByLabelText('Marka', { exact: true })).toHaveValue('FORD')
    expect(screen.getByLabelText('Model', { exact: true })).toHaveValue('TRANSIT')
    expect(screen.getByLabelText('Model yılı')).toHaveValue('2021')
    await waitFor(() => expect(port.catalog).toHaveBeenCalledWith('case-1', 'C'))
  })
  it('preserves manual changes during navigation and reapplies known case values only on request', async () => {
    const port = fixture()
    const current = sourceCase({ Marka: 'FORD', 'Araç Tipi': 'TRANSIT', 'Model Yılı': '2021', 'Araç Tarife Grubu': 'KAMYONET', 'Kasa Tipi': 'Panelvan' })
    const mounted = render(view(port, current))
    fireEvent.change(screen.getByLabelText('Marka', { exact: true }), { target: { value: 'Düzeltilmiş marka' } })
    fireEvent.change(screen.getByLabelText('Rayiç bedeli (TL)'), { target: { value: '1.000.000' } })
    mounted.unmount()
    render(view(port, current))
    expect(screen.getByLabelText('Marka', { exact: true })).toHaveValue('Düzeltilmiş marka')
    await userEvent.click(screen.getByRole('button', { name: 'Dosya bilgilerini al' }))
    expect(screen.getByLabelText('Marka', { exact: true })).toHaveValue('FORD')
    expect(screen.getByLabelText('Rayiç bedeli (TL)')).toHaveValue('1.000.000')
  })
  it('updates remembered automatic fields when the source changes and invalidates the old result', async () => {
    const port = fixture()
    const mounted = render(view(port)); await fill()
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' }))
    await screen.findByText(/55\.000,00/)
    const updated = sourceCase({ Marka: 'FORD', 'Araç Tipi': 'TRANSIT', 'Araç Tarife Grubu': 'KAMYONET', 'Kasa Tipi': 'Panelvan' })
    mounted.rerender(view(port, updated))
    expect(screen.getByLabelText('Araç türü')).toHaveValue('KAMYONET')
    expect(screen.getByLabelText('Marka', { exact: true })).toHaveValue('FORD')
    expect(screen.queryByText(/55\.000,00/)).not.toBeInTheDocument()
    expect(screen.getByLabelText('Model yılı')).toHaveValue('2024')
    expect(screen.getByLabelText('Rayiç bedeli (TL)')).toHaveValue('1.000.000')
    expect(screen.getByLabelText('1. parça adı')).toHaveValue('SOL ÇAMURLUK')
  })
  it('routes an unverified manufacturer/model to market values and invalidates an earlier reference amount', async () => {
    const port = fixture()
    render(view(port)); await fill()
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' }))
    await screen.findByText(/55\.000,00/)
    fireEvent.change(screen.getByLabelText('Marka', { exact: true }), { target: { value: 'Toyota' } })
    fireEvent.change(screen.getByLabelText('Model', { exact: true }), { target: { value: 'Corolla' } })
    expect(screen.queryByText(/55\.000,00/)).not.toBeInTheDocument()
    expect(screen.getByText(/Bu üretici, model ve yıl/)).toBeInTheDocument()
    expect(screen.getByLabelText('Hesap yöntemi')).toHaveValue('market_difference')
    fireEvent.change(screen.getByLabelText('Onarım sonrası piyasa değeri (TL)'), { target: { value: '900.000' } })
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' }))
    await waitFor(() => expect(port.calculate).toHaveBeenLastCalledWith('case-1', expect.objectContaining({ calculationBasis: 'market_difference', vehicleIdentity: { manufacturer: 'Toyota', model: 'Corolla' } })))
  })
  it('shows one calculation action and returns an amount without evidence, draft, approval or report steps', async () => {
    const port = fixture()
    render(view(port)); await fill()
    for (const text of ['Kanıtlar','Onaya Gönder','İnsan Onayı Ver','Sürüm Geçmişi','Nihai Rapor','Önizleme Oluştur']) expect(screen.queryByText(text)).not.toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' }))
    expect(await screen.findByText(/55\.000,00/)).toBeInTheDocument()
    expect(port.calculate).toHaveBeenCalledWith('case-1', expect.objectContaining({ marketValueMinor: 100_000_000, damageAmountMinor: 10_000_000, parts: [], partSelections: [expect.objectContaining({ stableRuleId: 'part-1', operation: 'replacement', quantity: 1 })] }))
  })
  it('invalidates an old result immediately and ignores a response if its inputs changed during the request', async () => {
    const port = fixture()
    render(view(port)); await fill()
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' })); await screen.findByText(/55\.000,00/)
    fireEvent.change(screen.getByLabelText('Kilometre'), { target: { value: '60000' } })
    expect(screen.queryByText(/55\.000,00/)).not.toBeInTheDocument()
    let resolve!: (value: typeof result) => void
    vi.mocked(port.calculate).mockImplementationOnce(() => new Promise(done => { resolve = done }))
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' }))
    fireEvent.change(screen.getByLabelText('Kilometre'), { target: { value: '70000' } })
    await act(async () => resolve(result))
    expect(screen.queryByText(/55\.000,00/)).not.toBeInTheDocument()
  })
  it('remembers inputs and amount across navigation and keeps another case or user isolated', async () => {
    const port = fixture()
    const current = render(view(port)); await fill()
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' })); await screen.findByText(/55\.000,00/)
    current.unmount()
    const reopened = render(view(port))
    expect(screen.getByLabelText('Kilometre')).toHaveValue('50000')
    expect(screen.getByText(/55\.000,00/)).toBeInTheDocument()
    reopened.rerender(view(port, { ...item, caseId: 'case-2' }))
    expect(screen.getByLabelText('Kilometre')).toHaveValue('')
    expect(screen.queryByText(/55\.000,00/)).not.toBeInTheDocument()
    reopened.rerender(view(port, item, { ...session, user: { ...session.user!, id: 'user-2' } }))
    expect(screen.getByLabelText('Kilometre')).toHaveValue('')
  })
  it('reveals repair prices only when required and rejects incomplete repair inputs', async () => {
    const port = fixture()
    render(view(port)); await fill()
    expect(screen.queryByLabelText('SOL ÇAMURLUK yeni parça bedeli')).not.toBeInTheDocument()
    await userEvent.selectOptions(screen.getByLabelText('SOL ÇAMURLUK işlemi'), 'repair')
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('yeni parça bedelini')
    expect(port.calculate).not.toHaveBeenCalled()
    await userEvent.click(screen.getByLabelText('Parça bedeli bilinmiyor'))
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' }))
    expect(await screen.findByText(/55\.000,00/)).toBeInTheDocument()
    expect(port.calculate).toHaveBeenCalledWith(item.caseId, expect.objectContaining({ partSelections: [expect.objectContaining({ operation: 'repair', partPriceAvailability: 'unavailable', newPartPriceMinor: null })] }))
  })
  it('does not invent a number when the server blocks a calculation and keeps the entered values', async () => {
    const port = fixture()
    vi.mocked(port.calculate).mockResolvedValue({ ...result, amountMinor: null, issues: [{ field: 'vehicleCondition', message: 'Ağır hasarlı araç için hesaplanamaz.' }] })
    render(view(port)); await fill()
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Ağır hasarlı')
    expect(screen.queryByText(/55\.000,00/)).not.toBeInTheDocument()
    expect(screen.getByLabelText('Rayiç bedeli (TL)')).toHaveValue('1.000.000')
  })
  it.each(['repair_paint', 'replacement_paint'] as const)('selects %s on one physical part and sends both supported operations', async operation => {
    const port = fixture()
    render(view(port)); await fill()
    await userEvent.selectOptions(screen.getByLabelText('SOL ÇAMURLUK işlemi'), operation)
    await userEvent.selectOptions(screen.getByLabelText('SOL ÇAMURLUK boya türü'), 'local')
    if (operation === 'repair_paint') await userEvent.click(screen.getByLabelText('Parça bedeli bilinmiyor'))
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' }))
    await screen.findByText(/55\.000,00/)
    expect(screen.getAllByText('SOL ÇAMURLUK', { selector: 'strong' })).toHaveLength(1)
    expect(port.calculate).toHaveBeenCalledWith(item.caseId, expect.objectContaining({ partSelections: [expect.objectContaining({ operation, paintMode: 'local' })] }))
    expect(screen.queryByText('Özel işlem')).not.toBeInTheDocument()
  })
  it('moves paintless repair into operations and clears its exclusion when switching back to repair and paint', async () => {
    const port = fixture()
    render(view(port)); await fill()
    await userEvent.selectOptions(screen.getByLabelText('SOL ÇAMURLUK malzemesi'), 'steel')
    await userEvent.selectOptions(screen.getByLabelText('SOL ÇAMURLUK işlemi'), 'paintless_repair')
    expect(screen.queryByLabelText('SOL ÇAMURLUK boya türü')).not.toBeInTheDocument()
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' })); await screen.findByText(/55\.000,00/)
    expect(port.calculate).toHaveBeenLastCalledWith(item.caseId, expect.objectContaining({ partSelections: [expect.objectContaining({ operation: 'paintless_repair', treatment: 'paintless_repair' })] }))
    await userEvent.selectOptions(screen.getByLabelText('SOL ÇAMURLUK işlemi'), 'repair_paint')
    await userEvent.click(screen.getByLabelText('Parça bedeli bilinmiyor'))
    await userEvent.click(screen.getByRole('button', { name: 'Hesapla' })); await screen.findByText(/55\.000,00/)
    expect(port.calculate).toHaveBeenLastCalledWith(item.caseId, expect.objectContaining({ partSelections: [expect.objectContaining({ treatment: 'standard', operation: 'repair_paint' })] }))
  })
  it('rejects duplicate physical parts and supports searching and keyboard selection without submitting', async () => {
    const port = fixture(), user = userEvent.setup()
    render(view(port)); await fill()
    await user.click(screen.getByRole('combobox', { name: 'Hasarlı parça' }))
    await user.type(screen.getByRole('combobox', { name: 'Hasarlı parça' }), 'camurluk')
    expect(within(screen.getByRole('listbox')).getAllByRole('option')).toHaveLength(1)
    await user.keyboard('{Enter}')
    expect(port.calculate).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Ekle' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Bu parça zaten eklendi')
    expect(screen.getAllByText('SOL ÇAMURLUK', { selector: 'strong' })).toHaveLength(1)
  })
  it('clears incompatible parts and switches mileage to working hours for group D', async () => {
    const port = fixture()
    render(view(port)); await fill()
    await userEvent.selectOptions(screen.getByLabelText('Araç türü'), 'İŞ MAKİNESİ')
    expect(screen.queryByText('SOL ÇAMURLUK', { selector: 'strong' })).not.toBeInTheDocument()
    expect(screen.getByLabelText('Çalışma saati')).toHaveValue('')
    await waitFor(() => expect(port.catalog).toHaveBeenLastCalledWith('case-1','D'))
  })
  it('records an unlisted part completely, requires market inputs and retains it across navigation', async () => {
    const port = fixture(), user = userEvent.setup()
    vi.mocked(port.calculate).mockResolvedValue({ ...result, amountMinor: 7_500_000, calculationMethod: 'market_value_difference' })
    const current = render(view(port))
    await user.click(screen.getByRole('button', { name: 'Listede olmayan parça ekle' }))
    await user.click(screen.getByRole('button', { name: 'Hesapla' }))
    expect(screen.getByRole('alert')).toHaveTextContent('adını')
    await user.type(screen.getByLabelText('1. parça adı'), 'Ön amortisör')
    fireEvent.change(screen.getByLabelText('Rayiç bedeli (TL)'), { target: { value: '1.000.000' } })
    await user.click(screen.getByRole('button', { name: 'Hesapla' }))
    expect(screen.getByRole('alert')).toHaveTextContent('Onarım sonrası piyasa değerini')
    expect(port.calculate).not.toHaveBeenCalled()
    fireEvent.change(screen.getByLabelText('Onarım sonrası piyasa değeri (TL)'), { target: { value: '900.000' } })
    fireEvent.change(screen.getByLabelText('Karşı taraf kusuru (%)'), { target: { value: '75' } })
    fireEvent.change(screen.getByLabelText('Ön amortisör konumu'), { target: { value: 'sol ön' } })
    await user.selectOptions(screen.getByLabelText('Ön amortisör malzemesi'), 'mechanical')
    await user.click(screen.getByRole('button', { name: 'Hesapla' }))
    expect(await screen.findByText(/75\.000,00/)).toBeInTheDocument()
    expect(port.calculate).toHaveBeenCalledWith(item.caseId, expect.objectContaining({ calculationBasis: 'market_difference', partSelections: [expect.objectContaining({ partName: 'Ön amortisör', position: 'sol ön', material: 'mechanical', stableRuleId: null })] }))
    current.unmount(); render(view(port))
    expect(screen.getByLabelText('1. parça adı')).toHaveValue('Ön amortisör')
    expect(screen.getByLabelText('Ön amortisör konumu')).toHaveValue('sol ön')
    expect(screen.getByText(/75\.000,00/)).toBeInTheDocument()
  })
  it('requires locations and market values for repeated known panels rather than multiplying their coefficient', async () => {
    const port = fixture(), user = userEvent.setup()
    render(view(port)); await fill()
    fireEvent.change(screen.getByLabelText('SOL ÇAMURLUK adedi'), { target: { value: '2' } })
    expect(screen.getByLabelText('Hesap yöntemi')).toHaveValue('market_difference')
    await user.click(screen.getByRole('button', { name: 'Hesapla' }))
    expect(screen.getByRole('alert')).toHaveTextContent('konumlarını')
    fireEvent.change(screen.getByLabelText('SOL ÇAMURLUK konumu'), { target: { value: '1. ve 2. bölüm' } })
    fireEvent.change(screen.getByLabelText('Onarım sonrası piyasa değeri (TL)'), { target: { value: '900.000' } })
    await user.click(screen.getByRole('button', { name: 'Hesapla' }))
    await screen.findByText(/55\.000,00/)
    expect(port.calculate).toHaveBeenCalledWith(item.caseId, expect.objectContaining({ calculationBasis: 'market_difference', partSelections: [expect.objectContaining({ quantity: 2, position: '1. ve 2. bölüm' })] }))
  })
  it('keeps differing physical positions independent when their material or operation changes', async () => {
    const port = fixture(), user = userEvent.setup()
    render(view(port)); await fill()
    fireEvent.change(screen.getByLabelText('SOL ÇAMURLUK konumu'), { target: { value: 'ön bölüm' } })
    await user.click(screen.getByRole('button', { name: 'Aynı parçaya farklı konum ekle' }))
    const positions = screen.getAllByLabelText('SOL ÇAMURLUK konumu')
    fireEvent.change(positions[1]!, { target: { value: 'arka bölüm' } })
    await user.selectOptions(screen.getAllByLabelText('SOL ÇAMURLUK malzemesi')[1]!, 'plastic_bodywork')
    expect(screen.getAllByLabelText('SOL ÇAMURLUK malzemesi')[0]).toHaveValue('unspecified')
    expect(screen.getAllByLabelText('SOL ÇAMURLUK malzemesi')[1]).toHaveValue('plastic_bodywork')
  })
  it('clears parts between vehicle types sharing a source group and updates body options', async () => {
    const port = fixture(), user = userEvent.setup()
    render(view(port)); await fill()
    await user.selectOptions(screen.getByLabelText('Araç türü'), 'TAKSİ')
    expect(screen.queryByText('SOL ÇAMURLUK', { selector: 'strong' })).not.toBeInTheDocument()
    expect(screen.getByLabelText('Kasa / araç yapısı')).toHaveValue('unspecified')
    await user.selectOptions(screen.getByLabelText('Araç türü'), 'MOTORSİKLET')
    expect(within(screen.getByLabelText('Kasa / araç yapısı')).getByRole('option', { name: 'Scooter' })).toBeInTheDocument()
    expect(within(screen.getByLabelText('Kasa / araç yapısı')).queryByRole('option', { name: 'Sedan' })).not.toBeInTheDocument()
  })
  it('preserves physical facts but removes incompatible coefficients when the body changes', async () => {
    const port = fixture(), user = userEvent.setup()
    render(view(port)); await fill()
    await user.selectOptions(screen.getByLabelText('Kasa / araç yapısı'), 'cabriolet')
    await user.click(screen.getByRole('combobox', { name: 'Hasarlı parça' }))
    await user.click(screen.getByRole('option', { name: 'SOL YAN PANEL (TİCARİ VE CABRİO)' }))
    await user.click(screen.getByRole('button', { name: 'Ekle' }))
    fireEvent.change(screen.getByLabelText('SOL YAN PANEL (TİCARİ VE CABRİO) konumu'), { target: { value: 'sol arka bölüm' } })
    await user.selectOptions(screen.getByLabelText('Kasa / araç yapısı'), 'sedan')
    expect(screen.getByLabelText('2. parça adı')).toHaveValue('SOL YAN PANEL (TİCARİ VE CABRİO)')
    expect(screen.getByLabelText('SOL YAN PANEL (TİCARİ VE CABRİO) konumu')).toHaveValue('sol arka bölüm')
    expect(screen.getByLabelText('Hesap yöntemi')).toHaveValue('market_difference')
  })
})
